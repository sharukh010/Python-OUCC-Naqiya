"""
+ - addition 
- - subtraction 
* - multiplication 
/ - division (float)
ex: 
5/2 = 2.5 
// - floor division (int)
ex: 
5//2 = 2 
% - modulo division (remainder)
ex: 
5 % 2 = 1 
** - power 
ex: 
2 ** 3 = 8 
"""
num1 = 5 
num2 = 2 

print("Addition:",num1 + num2) # 7
print("Subtraction:",num1-num2) # 3 
print("Multiplication:",num1 * num2) # 10
print("Division:",num1/num2) # 2.5 
print("Floor Division:",num1//num2) # 2 
print("Modulo Division:",num1 % num2) # 1 
print("Power:",num1 ** num2) # 25 