"""
Comparision operators: 
1. equals -> == 
2. lessthan -> < 
3. greater than -> > 
4. less than equals to -> <= 
5. greater than equals to -> >= 
6. not equals to -> != 
they will always give boolean as result 
if the comparision is true you will get true as result 
if the comparision is false you will get false as result 
"""
num1 = 10 
num2 = 20 

print(num1 == num2) # False 
print(num1 < num2) # True 
print(num1 > num2) # False 
print(num1 <= num2) # True 
print(num1 >= num2) # False 
print(num1 != num2) # True